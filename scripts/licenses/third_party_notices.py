#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md: the third-party components Vesper links, vendors or fetches, with their licences.

Rust crates come from `cargo tree -e normal` (what the shipped binaries link), Go modules from `go list -deps` over
the shim (what `containerd-shim-vesper-v2` links). Run from the repository root:

    python3 scripts/licenses/third_party_notices.py            # rewrite THIRD_PARTY_NOTICES.md
    python3 scripts/licenses/third_party_notices.py --check    # exit 1 if the file is out of date
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "THIRD_PARTY_NOTICES.md"

LICENCE_PATTERNS = [
    ("Apache-2.0", r"Apache License"),
    ("MPL-2.0", r"Mozilla Public License"),
    ("LGPL", r"GNU Lesser General Public"),
    ("GPL", r"GNU General Public"),
    ("ISC", r"ISC License"),
    ("MIT", r"Permission is hereby granted"),
    ("BSD-3-Clause", r"Neither the name"),
    ("BSD-2-Clause", r"Redistribution and use"),
]


def run(cmd: list[str], cwd: Path) -> str:
    return subprocess.run(cmd, cwd=cwd, check=True, capture_output=True, text=True).stdout


def rust_crates() -> list[tuple[str, str, str]]:
    out = run(["cargo", "tree", "-e", "normal", "--prefix", "none", "--format", "{p}\t{l}", "--locked"], ROOT)
    rows = set()
    for line in out.splitlines():
        if "\t" not in line:
            continue
        pkg, lic = line.split("\t", 1)
        parts = pkg.split()
        if len(parts) < 2 or parts[0] == "vesper":
            continue
        rows.add((parts[0], parts[1].lstrip("v"), lic.strip() or "UNKNOWN"))
    return sorted(rows)


def detect_licence(directory: Path) -> str:
    for candidate in sorted(directory.iterdir()) if directory.is_dir() else []:
        if re.match(r"(?i)^(licen[cs]e|copying)", candidate.name) and candidate.is_file():
            text = candidate.read_text(errors="replace")[:4000]
            for name, pattern in LICENCE_PATTERNS:
                if re.search(pattern, text):
                    return name
            return "see " + candidate.name
    return "UNKNOWN"


def go_modules() -> list[tuple[str, str, str]]:
    shim = ROOT / "shim"
    fmt = "{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}"
    out = run(["go", "list", "-deps", "-f", fmt, "./..."], shim)
    rows = set()
    for line in out.splitlines():
        if line.count("\t") != 2:
            continue
        path, version, directory = line.split("\t")
        rows.add((path, version, detect_licence(Path(directory))))
    return sorted(rows)


STATIC_HEAD = """# Third-party notices

Vesper is licensed under the Business Source License 1.1 ([LICENSE](LICENSE)). It uses the third-party components
below, each under its own licence. This file is generated by `scripts/licenses/third_party_notices.py`; do not edit
it by hand (`make third-party-notices`).

## Vendored in this repository

| Component | Path | Licence |
|---|---|---|
| Firecracker OpenAPI definition (pinned revision in `docs/specs/design-v0.baselines.lock.yaml`) | `third_party/firecracker/` | Apache-2.0; see `third_party/firecracker/LICENSE` and `NOTICE` |
| `llm-council` agent skill | `.codex/skills/llm-council/` | Apache-2.0; see `.codex/skills/llm-council/LICENSE.txt` |

## Fetched at build time, not redistributed

`make systemvm-fetch` and `make systemvm-overlay` download these on the developer's machine from their upstream
sources, verified against the digests pinned in `docs/specs/systemvm-image.lock.yaml`,
`docs/specs/systemvm-packages.lock.yaml` and `systemvm/archives.yaml`. Vesper starts them as separate programs
inside the System VM and does not link them. Anyone who redistributes a built System VM image takes on the
obligations of each component's licence, including offering the corresponding source of the GPL and LGPL parts.

| Component | Licence |
|---|---|
| Alpine Linux `virt` boot image (Linux kernel, BusyBox, musl, OpenRC) | GPL-2.0 (kernel, BusyBox), MIT (musl), BSD-2-Clause (OpenRC) |
| Firecracker and jailer release binaries | Apache-2.0 (the release bundle includes libseccomp-derived filters, LGPL-2.1) |
| containerd, `ctr`, runc, Docker Engine and CLI | Apache-2.0 |
| socat, iptables, e2fsprogs, qemu-x86_64 (user-mode emulation) | GPL-2.0 (e2fsprogs libraries LGPL-2.0 / BSD) |
| glib, libmount | LGPL-2.1 |
| readline | GPL-3.0 |
| libmnl, libnftnl | LGPL-2.1 / GPL-2.0 |
| tini | MIT |
| unfs3 (once added, GH #160) | BSD-3-Clause |
| ca-certificates | MPL-2.0 (certificate data) |
| Upstream Firecracker CI images and test artefacts (only for parity runs) | Apache-2.0 and the licences of each guest image |
"""


def render() -> str:
    lines = [STATIC_HEAD]
    crates = rust_crates()
    lines.append(f"## Rust crates linked into the Vesper binaries ({len(crates)})\n")
    lines.append("| Crate | Version | Licence |\n|---|---|---|")
    lines += [f"| {n} | {v} | {lic} |" for n, v, lic in crates]
    mods = go_modules()
    lines.append(f"\n## Go modules linked into `containerd-shim-vesper-v2` ({len(mods)})\n")
    lines.append("| Module | Version | Licence |\n|---|---|---|")
    lines += [f"| {p} | {v} | {lic} |" for p, v, lic in mods]
    lines.append(
        "\nWhere a crate is offered under a choice of licences (for example `MIT OR Apache-2.0`), Vesper uses it "
        "under a permissive option. Where an Apache-2.0 dependency ships a NOTICE file, that file is reproduced in "
        "its source distribution, which `Cargo.lock` and `shim/go.sum` pin.\n"
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if THIRD_PARTY_NOTICES.md is out of date")
    args = parser.parse_args()
    text = render()
    unknown = [line for line in text.splitlines() if line.endswith("| UNKNOWN |")]
    if unknown:
        print("third-party-notices: licence not detected for:\n  " + "\n  ".join(unknown), file=sys.stderr)
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("third-party-notices: THIRD_PARTY_NOTICES.md is out of date (fix: make third-party-notices)",
                  file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
