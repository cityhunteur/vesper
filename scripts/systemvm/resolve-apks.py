#!/usr/bin/env python3
"""Resolve the Alpine package closure for the System VM extras and pin it.

Usage: resolve-apks.py --branch v3.22 --arch aarch64 --base-index ISO_APKINDEX
                        --index main=PATH --index community=PATH --cache DIR
                        --out docs/specs/systemvm-packages.lock.yaml PKG...

Reads APKINDEX files (already extracted), resolves dependencies by package
name, `so:`/`cmd:`/path provides and version constraints, treats packages in
the base index (the boot ISO's apks/) as present, downloads every package of
the closure into DIR, computes SHA-256, and writes the lock. Standard library
only. Deterministic: packages are emitted sorted by name.
"""
import argparse
import hashlib
import os
import re
import sys
import urllib.request

MIRROR = "https://dl-cdn.alpinelinux.org/alpine"


def parse_index(path, repo):
    packages = {}
    with open(path, encoding="utf-8") as handle:
        for block in handle.read().split("\n\n"):
            entry = {}
            for line in block.splitlines():
                if len(line) > 1 and line[1] == ":":
                    entry.setdefault(line[0], line[2:])
            if "P" in entry:
                entry["repo"] = repo
                packages[entry["P"]] = entry
    return packages


def providers(indexes):
    """Map every provided name (package, so:, cmd:, path) to candidate entries in index order."""
    table = {}
    for index in indexes:
        for name, entry in index.items():
            table.setdefault(name, []).append(entry)
            for provided in entry.get("p", "").split():
                table.setdefault(provided.split("=")[0], []).append(entry)
    return table


def dep_name(dep):
    dep = dep.lstrip("!")
    return re.split(r"[<>=~]", dep, 1)[0]


def resolve(roots, base, extra_indexes, include_base=()):
    base_providers = providers([base])
    all_providers = providers(extra_indexes + [base])
    chosen = {}
    queue = list(roots)
    while queue:
        dep = queue.pop(0)
        if dep.startswith("!"):
            continue  # conflicts are not installed
        name = dep_name(dep)
        if name in base_providers and name not in include_base:
            continue  # the boot media already ships it (apk resolves it from /media/*/apks)
        candidates = all_providers.get(name)
        if not candidates:
            raise SystemExit(f"no provider for dependency {dep!r}")
        entry = candidates[0]
        if entry["P"] in chosen:
            continue
        chosen[entry["P"]] = entry
        queue.extend(entry.get("D", "").split())
    return chosen


def sha256_of(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--branch", required=True)
    parser.add_argument("--arch", required=True)
    parser.add_argument("--base-index", required=True)
    parser.add_argument("--index", action="append", default=[], help="repo=PATH")
    parser.add_argument("--cache", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--include-base", action="append", default=[], help="pin this package although the boot media ships it (it is not installed by default)")
    parser.add_argument("--extra-yaml", help="file appended verbatim to the lock (for example an archives: section)")
    parser.add_argument("packages", nargs="+")
    args = parser.parse_args()

    base = parse_index(args.base_index, "iso")
    extras = []
    for spec in args.index:
        repo, path = spec.split("=", 1)
        extras.append(parse_index(path, repo))
    chosen = resolve(args.packages, base, extras, set(args.include_base))

    os.makedirs(args.cache, exist_ok=True)
    lines = [
        "# Pinned Alpine packages installed into the System VM at boot (WOR-25 / GH #13, #14).",
        "# Generated by scripts/systemvm/resolve-apks.py; every file is signed by Alpine and digest-pinned here.",
        "# Read by: systemvmctl (src/systemvm/packages.rs) and scripts/systemvm/fetch-packages.sh.",
        "schema_version: 2",
        f"branch: {args.branch}",
        f"arch: {args.arch}",
        f"requested: [{', '.join(args.packages)}]",
        "packages:",
    ]
    for name in sorted(chosen):
        entry = chosen[name]
        file_name = f"{name}-{entry['V']}.apk"
        url = f"{MIRROR}/{args.branch}/{entry['repo']}/{args.arch}/{file_name}"
        path = os.path.join(args.cache, file_name)
        if not os.path.exists(path):
            print(f"downloading {url}", file=sys.stderr)
            urllib.request.urlretrieve(url, path + ".part")
            os.replace(path + ".part", path)
        lines.append(f"  - name: {name}")
        lines.append(f"    version: \"{entry['V']}\"")
        lines.append(f"    repo: {entry['repo']}")
        lines.append(f"    file: {file_name}")
        lines.append(f"    url: {url}")
        lines.append(f"    sha256: {sha256_of(path)}")
        lines.append(f"    size_bytes: {os.path.getsize(path)}")
    if args.extra_yaml:
        with open(args.extra_yaml, encoding="utf-8") as handle:
            lines.append(handle.read().rstrip("\n"))
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"pinned {len(chosen)} packages to {args.out}")


if __name__ == "__main__":
    main()
